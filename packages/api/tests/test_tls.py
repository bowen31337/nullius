def test_the_entrypoint_serves_https_when_the_pair_is_there(
    test_database_url: str, tmp_path: Path
) -> None:
    """The sentence's success case, end to end.

    The subprocess is told to bind ``0.0.0.0`` — a non-loopback host,
    which is the case the feature is about — *with* the pair
    configured, and the test reaches it over ``127.0.0.1``, which the
    any-interface bind answers.  It is a real HTTPS server: the
    connection is verified against the fixture's own certificate, so a
    process that bound cleartext would fail the handshake rather than
    quietly pass.
    """
    certificate, key = write_self_signed_certificate(tmp_path)
    token_file = write_token_file(tmp_path / "tokens.json")
    port = _free_port()
    environment = _bootstrap_env(test_database_url, token_file)
    environment[TLS_CERT_ENV] = certificate
    environment[TLS_KEY_ENV] = key
    environment["NULLIUS_API_PORT"] = str(port)

    process = subprocess.Popen(
        [sys.executable, "-m", "nullius_api"],
        env=environment,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    try:
        status, body = _poll_https(port, certificate, "/metrics/fdr-deploy")
        assert status == 200
        assert body == {
            "history": [],
            "campaign_id": None,
            "fdr_deploy": None,
            "computed_at": None,
        }
        # …and the server is still serving, not exited after one answer.
        assert process.poll() is None
    finally:
        process.terminate()
        try:
            process.wait(timeout=10)
        except subprocess.TimeoutExpired:  # pragma: no cover - defensive
            process.kill()
            process.wait(timeout=10)


def _free_port() -> int:
    """A port the kernel confirms free — bound then released, so the
    entrypoint can take it back."""
    with socket.socket() as probe:
        probe.bind(("127.0.0.1", 0))
        return probe.getsockname()[1]


def _poll_https(port: int, certificate: str, path: str) -> tuple[int, dict]:
    """Poll an HTTPS server until it answers, then return its answer.

    Polling a *verified* HTTPS connection means a server that had not
    yet finished binding, or that bound cleartext, keeps being retried
    until the deadline — the assertion is on the answer, not on the
    first connection attempt.
    """
    context = ssl_client_context(certificate)
    deadline = time.monotonic() + 60.0
    last: Exception | None = None
    while time.monotonic() < deadline:
        try:
            connection = http.client.HTTPSConnection(
                "127.0.0.1", port, timeout=5, context=context
            )
            try:
                connection.request(
                    "GET",
                    path,
                    headers={"Authorization": f"Bearer {token_for('metrics:read')}"},
                )
                response = connection.getresponse()
                return response.status, json.loads(response.read().decode("utf-8"))
            finally:
                connection.close()
        except OSError as exc:
            last = exc
            time.sleep(0.3)
    raise AssertionError(f"the HTTPS entrypoint never answered: {last!r}")
