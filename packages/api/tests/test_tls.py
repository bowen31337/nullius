"""Feature 21: a non-loopback bind is HTTPS, or no server at all.

*System refuses to bind a non-loopback host unless NULLIUS_API_TLS_CERT
and NULLIUS_API_TLS_KEY name a certificate and key, which returns a
startup error message naming the missing file, and serves HTTPS through
the standard library's ssl module when they do, so a bearer token never
crosses a network in cleartext.*

Each clause is pinned here as its own set of cases, in the order the
sentence states them:

* *refuses to bind a non-loopback host unless…* — the classification
  (:func:`~nullius_api.tls.is_loopback_host`) and the demand
  (:meth:`~nullius_api.tls.TlsConfig.resolve`), including the loopback
  default that needs nothing and the several non-loopback spellings
  that need everything;
* *…returns a startup error message naming the missing file* — one
  plain sentence per failure, naming the variable and the path, with no
  traceback, no file contents, and exit status 2 through the real
  entrypoint;
* *…serves HTTPS through the standard library's ssl module when they
  do* — a live server over a real TLS socket, a cleartext connection to
  the same port failing the handshake, and the token gate still standing
  inside the tunnel.

The certificate is generated by the suite's own fixture
(:func:`conftest.write_self_signed_certificate`) rather than checked in,
and the client verifies it against that exact file — so *serves HTTPS*
is proven by a handshake that would fail against any other certificate,
not by a connection that merely succeeded.
"""

