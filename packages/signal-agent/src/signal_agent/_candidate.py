def _has_table(connection: sqlite3.Connection, table: str) -> bool:
    """Whether the database holds ``table`` yet — a read of ``sqlite_master``."""
    return connection.execute(_TABLE_EXISTS_SQL, (table,)).fetchone() is not None


def _persist(path: Path, reading: ModelDiscrimination) -> None:
    """Write the reading into this member's table, idempotently by the pair.

    Owns the connection because it is the *second* transaction: the attribution,
    the halves and the arithmetic all happened first, in
    :func:`mechanism_discrimination_by_model`'s connection, so a refused reading
    never opens a write at all — feature 123's ordering, and the reason its
    ``guard`` measures before it touches the store.

    ``CREATE TABLE IF NOT EXISTS`` on every call, the contract every store in
    this workspace states: a fresh database and one this build has written to a
    hundred times must both work, and a member-owned table is the one piece of
    DDL this member is entitled to run.  The ``ON CONFLICT`` upsert is 214's,
    widened to the composite key — the grain is the ``(campaign, model)`` pair, so
    a re-reading refreshes the row rather than appending a second one.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    with closing(sqlite3.connect(path)) as connection, connection:
        connection.execute(_SCHEMA)
        connection.execute(
            f"INSERT INTO {CANDIDATE_TABLE} ({', '.join(_COLUMNS)}) "
            f"VALUES ({', '.join('?' for _ in _COLUMNS)}) "
            f"ON CONFLICT(campaign_id, model) DO UPDATE SET "
            f"correlation = excluded.correlation, "
            f"interval_lower = excluded.interval_lower, "
            f"interval_upper = excluded.interval_upper, "
            f"pairs = excluded.pairs, runs = excluded.runs, "
            f"proposals = excluded.proposals, "
            f"policy_version = excluded.policy_version, "
            f"cohort_digest = excluded.cohort_digest, "
            f"seen_at = excluded.seen_at",
            (
                reading.campaign_id,
                reading.model,
                reading.correlation,
                reading.lower,
                reading.upper,
                reading.pairs,
                reading.runs,
                reading.proposals,
                reading.policy_version,
                reading.cohort_digest,
                reading.seen_at.isoformat(),
            ),
        )
