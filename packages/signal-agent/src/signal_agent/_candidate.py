"""Feature 216 — ``mechanism_discrimination``, persisted per candidate model.

*"System persists mechanism_discrimination per candidate model before the gate
milestone, so a weak agent is not misread as a failed thesis."*

docs/nullius-tech-architecture.md §14.1 states the instrument feature 214
persists per campaign, and the sentence that makes the *per-model* half a
requirement rather than a refinement (§14.1)::

    **Run this at M2, before the M3 gate.**  Two campaigns per candidate model,
    roughly $60.  Skip it and a weak signal agent will present as a failed
    thesis, and you will disprove the wrong hypothesis.

and §14.1's mitigation 3 says what the stratified form is for::

    **Record and stratify.**  ``agent_model_id`` is indexed for exactly this;
    report M3 results per model stratum as well as pooled.

docs/alpha-engine-prd.md §13 invariant 5a states the same as an invariant::

    Every node records ``agent_model_id``.  Provider aliases re-route silently;
    a pinned snapshot or a self-hosted checkpoint hash is the only real
    guarantee.  **M3 results are reported per model stratum as well as pooled.**

**The risk row is the sentence's purpose clause, verbatim.**  PRD §14::

    | Signal agent too weak, read as a failed thesis | High | Measure
    | ``mechanism_discrimination`` at M2, before the gate (arch §14.1) |

so the feature is the *stratification* that row's detection depends on: a pooled
figure over a mixed pool attributes a weak agent's collapsed correlation to the
campaign, and the campaign's failure is then read as the thesis's.

**What this module is, in one line.**  Feature 214 persists the figure **per
campaign**; this persists the same figure **per candidate model**, into a table
this member owns, keyed by the ``(campaign, model)`` pair — §14.1's *"two
campaigns per candidate model"* being the reason the campaign stays in the key.

**What this module is not.**

* It is not feature 214, and 214 is edited nowhere.  That feature's row is the
  *pooled* (well — the campaign-scoped) reading and stays exactly as its own
  suite pins it; this feature cannot produce that row, and 214 cannot produce
  this one.
* It is not feature 215's count, although 215 is the nearest neighbour in one
  respect worth stating so a reader does not confuse the two: 215 *derives* its
  per-model strata by grouping a campaign's whole proposal history, and returns a
  mapping with no row behind it.  Here the model is a **declared and verified**
  input and the figure is **written down** — see "the stratum is verified, never
  derived".
* It is not a gate, a milestone or a verdict.  No milestone is a *value* in this
  workspace (§14.1's M2/M3 appear in code only as citations, and feature 187's
  ``bootstrap._claim`` takes the gate's world count as a caller-supplied keyword
  precisely because the gate is not a stored state), so "before the gate
  milestone" is discharged the only way it can be — as a *structural* claim about
  what this module reads; see :data:`GATE_SQL_TABLES` and the suite case that
  pins it.
* It is not a pooled figure, and cannot be asked for one: there is no default
  model and no "all models" read.  See "there is no default, and no pooled
  answer".

**The stratum is verified, never derived.**  A cohort is the one thing this
member may not assemble after the fact (§14.1 rule 1, argued at 214's
``_validated_cohort``), and at M2 a campaign *is* a candidate model's unit — so
the tempting implementation is to group the declared cohort by
``node.agent_model_id`` and write one row per bucket.  Refused, for a reason that
is the whole point of the sentence: §14.1 records the provenance failure as
*"not hypothetical"* — DeepSeek retired ``deepseek-v4-flash`` in September 2026
while continuing to accept the ID, so two campaigns under one model string were
generated by **different models**.  A deriving implementation would take that
mixed pool and report two tidy small-``n`` strata, which is exactly the flattering
shape; a *declaring* implementation refuses it by name and sends the operator to
:class:`CandidateModelError`.  What §14.1's mitigation 3 asks of a *derivation*
is the M3 paired comparison — a different feature over a different table — while
the M2 instrument is asked to **measure a candidate model**, and a figure
attributed to a model that did not author every branch in it is the misreading
this feature exists to prevent.

**There is no default, and no pooled answer.**  A missing, blank or non-string
model is refused, and the signature has no shape that omits one.  The failure the
sentence names — *"a weak agent is not misread as a failed thesis"* — is a
*failure of pooling*, so a default would restore it by omission.  That is 214's
argument for refusing a default cohort (*"a caller that could just correlate
everything would get a number that silently mixes the exactly-zero half"*) made
one level up: here the thing a default would silently mix is a second agent.  The
pooled figure is not lost — it is 214's, one call away, in
``campaign_discrimination``; what this feature declines is producing it *instead
of* the stratified one.

**One thing this module restates, and one thing it does not.**  It **does not**
restate the arithmetic.  A second ``_pearson`` here would be a second definition
of §14.1's statistic and a second definition of the Fisher-z interval its rule 3
requires, so this module imports both from :mod:`signal_agent._discrimination`,
together with the two half-reads, the two store-shape checks and 214's own
:class:`~signal_agent.MechanismDiscrimination` — the precedent for reaching a
sibling inside the member being feature 213's ``_themes._SLUG_RE``, reached
*"through :mod:`signal_agent._themes` rather than re-spelled"*.  It **does**
restate every name it reads (``node_proposal``, ``node``, ``agent_model_id``,
``replay_score``, ``campaign``), for the reason every store in this workspace
restates its own — and the member's own suite asserts the two spellings agree
rather than leaving them to drift.

**What "the halves" means here.**  The in-sample half is 214's
:data:`~signal_agent.IS_GAIN_METRIC` — ``ir_marginal``, read from the snapshot
207 froze beside each proposal rather than from ``node``'s live column, because
feature 240 refreshes that row in place.  The out-of-sample half is the mean of
the ``replay_score`` rows whose ``committed_pick`` is the branch.  A branch is
**one point** at the mean of its runs, because §14.1's unit is the branch.  Both
are read by 214's functions, so the two figures over one cohort cannot disagree
about what a branch's gain is.

**The frozen cohort, and why this digest differs from 214's.**  §14.1 rule 1:
*"Freeze the cohort before any model runs, and hash its inputs."*  The model is
an input to a model-scoped figure, so :func:`_cohort_digest` hashes it in the
header lines beside the campaign, the revision and the metric.  Measuring one
campaign's one model with both features over the *same* branch list therefore
yields two **different** digests — and that is the honest reading rather than a
defect: the two rows are two different readings, and a colliding digest would
claim they were the same inputs.  What 214's plan sentence asks for is the
*mechanism* — *"so 216's stratified reading can be shown to be over the same
inputs"* — and this row is auditable exactly the way that row is: a report
publishes the figure and the hash of the branches and gains behind it.

**Why no component, and why no seat.**  The reading resolves no configuration of
its own: the tables, the column, the metric pair and the figure's shape are all
facts about state two existing component builders already expose (207's store and
the tree it lives in).  So it is a free function beside them, reached as
``from signal_agent import mechanism_discrimination_by_model``, exactly as feature
186's :func:`bootstrap.world_census` sits beside the bootstrap pool, 215's
``tree_diversity`` sits beside the history store and 214's
``mechanism_discrimination`` sits beside this one.  A tenth ``signal-agent-*``
registration would put a name in the registry for a question that composes
nothing, and this feature has no *composed component* to read.

Stdlib only (plus this member's own modules), and import-cheap: no third-party
import at module scope, so the factory's scan — which imports this member to fire
its ``@register`` builders — pays nothing for this module.
"""

