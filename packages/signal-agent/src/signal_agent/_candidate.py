def _validated_model(value: Any) -> str:
    """Validate the candidate model: a non-blank string, and not a flag.

    The floor of the feature, and the argument for it is decision 2 above: the
    failure the sentence names is a *pooled* reading, so there is no default here
    to fall back to and no way to ask for "the figure" without naming who it is
    about.  ``bool`` is refused explicitly because ``True`` is ``1`` in Python —
    the trap 214's ``_validated_count`` and 215's ``_validated_model`` each name
    for their own arguments.

    The value is returned **verbatim, stripped of nothing**.  203's
    :func:`providers.require_agent_model_id` owns what a model id may be, and
    this module only refuses the ones that name no model at all rather than
    reshaping one that does — 215's rule for the same column, and the reason a
    dropped trailing space here would silently merge two strata.
    """
    if isinstance(value, bool) or not isinstance(value, str) or not value.strip():
        raise CandidateModelError(
            f"the candidate model is {value!r} ({type(value).__name__}) rather "
            f"than a non-empty model id: feature 216's sentence is *persists "
            f"mechanism_discrimination per candidate model*, §14.1 budgets two "
            f"campaigns per candidate model, and a reading that names no model "
            f"cannot be printed as a stratum beside the real ones — which is the "
            f"pooled reading the sentence exists to prevent, and the reason this "
            f"argument has no default (feature 216)."
        )
    return value


def _validated_cohort_size(value: Any, *, name: str) -> int:
    """Validate one denominator: a whole number, not a flag, not negative."""
    if isinstance(value, bool) or not isinstance(value, int):
        raise CandidateModelError(
            f"a candidate-model reading's {name} is {value!r} "
            f"({type(value).__name__}) rather than a whole number: it is how "
            f"many {'branches the figure is over' if name == 'pairs' else 'proposals this model wrote'} "
            f"and a value that is not a count is a reading no measurement could "
            f"produce. ``bool`` is refused explicitly because ``True`` is ``1`` "
            f"in Python (feature 216)."
        )
    if value < 0:
        raise CandidateModelError(
            f"a candidate-model reading's {name} cannot be negative — got "
            f"{value!r}: a cohort holds zero branches or more (feature 216)."
        )
    return value


